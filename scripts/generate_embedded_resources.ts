// Writes cli/EmbeddedResources.generated.ts, which imports every standard
// library file as text. `bun build --compile` bundles those imports, so a lone
// `bpl` executable can compile programs (see compiler/common/EmbeddedHome.ts).
// Pass --check to verify the committed module lists the current files.
import { readdirSync, readFileSync, writeFileSync } from "fs";
import { join, relative } from "path";

const root = join(import.meta.dir, "..");
const libDir = join(root, "lib");
const outputPath = join(root, "cli", "EmbeddedResources.generated.ts");

/** Runtime inputs the compiler links or compiles, besides BPL modules. */
const LIB_RUNTIME_FILES = [
  "runtime_support.c",
  "runtime_wasm.ll",
  "runtime_wasm_host.ll",
];

function libModules(dir: string): string[] {
  const files: string[] = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (entry.name.startsWith(".")) continue;
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      files.push(...libModules(full));
    } else if (/\.(bpl|x)$/.test(entry.name)) {
      files.push(relative(libDir, full).split("\\").join("/"));
    }
  }
  return files;
}

export function generateEmbeddedResources(): string {
  const libFiles = [...libModules(libDir), ...LIB_RUNTIME_FILES].sort();
  const imports: string[] = [];
  const entries: string[] = [];
  libFiles.forEach((file, index) => {
    imports.push(
      `import lib${index} from "../lib/${file}" with { type: "text" };`,
    );
    entries.push(`  [${JSON.stringify(file)}, lib${index}],`);
  });
  return [
    "// Generated by scripts/generate_embedded_resources.ts; do not edit by hand.",
    ...imports,
    "",
    "/** Standard library files by path relative to `lib/`. */",
    "export const EMBEDDED_LIB_FILES: ReadonlyArray<",
    "  readonly [path: string, content: string]",
    "> = [",
    ...entries,
    "];",
    "",
  ].join("\n");
}

if (import.meta.main) {
  const generated = generateEmbeddedResources();
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(outputPath, "utf8");
    } catch {}
    if (current !== generated) {
      console.error(
        "cli/EmbeddedResources.generated.ts is out of date; run `bun run generate:embedded`.",
      );
      process.exit(1);
    }
  } else {
    writeFileSync(outputPath, generated);
  }
}
